<?php

namespace App\Livewire;

use App\Models\Category;
use App\Models\DailyLog;
use App\Models\FocusSession;
use App\Models\Step;
use App\Models\WeeklyGoal;
use Livewire\Attributes\Layout;
use Livewire\Component;

#[Layout('layouts.app')]
class ExportData extends Component
{
    public string $lastExport = '';

    public function exportJson()
    {
        $data = [
            'exported_at' => now()->toISOString(),
            'categories' => Category::with(['steps' => function ($q) {
                $q->with('children')->orderBy('sort_order');
            }])->ordered()->get()->toArray(),
            'focus_sessions' => FocusSession::with('category')->orderBy('started_at')->get()->toArray(),
            'daily_logs' => DailyLog::orderBy('date')->get()->toArray(),
            'weekly_goals' => WeeklyGoal::orderBy('week_start')->get()->toArray(),
        ];

        $json = json_encode($data, JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE);
        $filename = 'progress-tracker-export-' . now()->format('Y-m-d') . '.json';

        $this->lastExport = $filename;

        return response()->streamDownload(function () use ($json) {
            echo $json;
        }, $filename, ['Content-Type' => 'application/json']);
    }

    public function exportMarkdownReview()
    {
        $weekStart = today()->startOfWeek();
        $weekEnd = $weekStart->copy()->endOfWeek();

        $stepsCompleted = Step::where('status', 'done')
            ->whereBetween('completed_at', [$weekStart, $weekEnd])
            ->with('category')
            ->get();

        $focusSessions = FocusSession::completed()
            ->whereBetween('started_at', [$weekStart, $weekEnd])
            ->get();

        $totalMinutes = (int) $focusSessions->sum('duration_minutes');
        $logs = DailyLog::whereBetween('date', [$weekStart->toDateString(), $weekEnd->toDateString()])->get();

        $md = "# Weekly Review: {$weekStart->format('M j')} - {$weekEnd->format('M j, Y')}\n\n";
        $md .= "## Summary\n\n";
        $md .= "- **Steps completed:** {$stepsCompleted->count()}\n";
        $md .= "- **Focus time:** " . intdiv($totalMinutes, 60) . "h " . ($totalMinutes % 60) . "m\n";
        $md .= "- **Days logged:** {$logs->count()} / 7\n";
        if ($logs->avg('focus_rating')) {
            $md .= "- **Avg focus rating:** " . number_format($logs->avg('focus_rating'), 1) . " / 5\n";
        }
        $md .= "\n## Completed Steps\n\n";

        foreach ($stepsCompleted->groupBy(fn($s) => $s->category?->name ?? 'General') as $catName => $steps) {
            $md .= "### {$catName}\n\n";
            foreach ($steps as $step) {
                $md .= "- [x] {$step->title}\n";
            }
            $md .= "\n";
        }

        if ($logs->isNotEmpty()) {
            $md .= "## Daily Logs\n\n";
            foreach ($logs as $log) {
                $md .= "### {$log->date->format('l, M j')}\n\n";
                if ($log->daily_goal) $md .= "- **Goal:** {$log->daily_goal}\n";
                $md .= "- **Focus:** {$log->focus_rating}/5";
                if ($log->energy_level) $md .= " | **Energy:** {$log->energy_level}/5";
                if ($log->mood) $md .= " | **Mood:** {$log->mood}/5";
                $md .= "\n";
                if ($log->notes) $md .= "- {$log->notes}\n";
                $md .= "\n";
            }
        }

        $md .= "\n---\n*Generated by Progress Tracker on " . now()->format('Y-m-d H:i') . "*\n";

        $filename = 'weekly-review-' . $weekStart->format('Y-m-d') . '.md';

        return response()->streamDownload(function () use ($md) {
            echo $md;
        }, $filename, ['Content-Type' => 'text/markdown']);
    }

    public function render()
    {
        return view('livewire.export-data');
    }
}
